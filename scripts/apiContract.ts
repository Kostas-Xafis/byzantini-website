/**
 * Generates `lib/api/contract.ts` — the browser-safe API contract — from the server route registry.
 *
 *   bun run api:contract           write the file
 *   bun run api:contract --check   exit 1 if the committed file differs from what the registry produces
 *
 * The contract carries only what a browser needs to build a request (`method`, `path`, `multipart`,
 * `rawBlob`): no handlers, no SQL, no Zod schemas, no env names. Client code reaches it through
 * `@routes/index.client`; the server registry (`lib/api/routes`) stays server-only.
 */
import { routeEntries } from "../lib/api/routes";

const OUTPUT = new URL("../lib/api/contract.ts", import.meta.url);
const check = process.argv.includes("--check");

const HEADER = `/**
 * GENERATED by \`scripts/apiContract.ts\` — DO NOT EDIT. Regenerate with \`bun run api:contract\`.
 *
 * Browser-safe API contract: endpoint key → what a client needs to build the request. Derived from the
 * server route registry (\`lib/api/routes\`), which must never reach the browser bundle.
 * Drift is caught three ways: \`satisfies\` below (key set), \`ContractInSync\` in \`lib/api/types.ts\`
 * (method/path literals) and \`tests/unit/apiContract.test.ts\` (every field, at runtime).
 */`;

/** A string literal the way prettier prints it: double quotes, unless the value has more `"` than `'`. */
function quote(value: string): string {
	const doubles = value.split('"').length - 1;
	const singles = value.split("'").length - 1;
	if (doubles <= singles) return JSON.stringify(value);
	return `'${value.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
}

function render(): string {
	const lines = routeEntries().map(([endpoint, route]) => {
		const entry = `{ method: ${quote(route.method)}, path: ${quote(route.path)}, multipart: ${route.multipart}, rawBlob: ${route.rawBlob} }`;
		return `\t${quote(endpoint)}: ${entry},`;
	});
	return [
		HEADER,
		`import type { APIContractEntry, APIEndpointNames } from "./types";`,
		``,
		`export const APIEndpoints = {`,
		...lines,
		`} as const satisfies Record<APIEndpointNames, APIContractEntry>;`,
		``,
	].join("\n");
}

const expected = render();
const file = Bun.file(OUTPUT);
const current = (await file.exists()) ? await file.text() : "";

if (check) {
	if (current !== expected) {
		console.error("lib/api/contract.ts is out of date with the route registry — run `bun run api:contract` and commit the result.");
		process.exit(1);
	}
	console.log(`lib/api/contract.ts is up to date (${routeEntries().length} endpoints).`);
} else if (current === expected) {
	console.log(`lib/api/contract.ts already up to date (${routeEntries().length} endpoints).`);
} else {
	await Bun.write(OUTPUT, expected);
	console.log(`Wrote lib/api/contract.ts (${routeEntries().length} endpoints).`);
}
